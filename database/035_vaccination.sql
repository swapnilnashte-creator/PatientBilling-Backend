-- Vaccination tracking: the hospital's vaccine list, a dose schedule, and each patient's doses.
-- Switched on per hospital. The schedule must be approved by an Admin or a doctor before due dates are shown.
ALTER TABLE hospitals
  ADD COLUMN IF NOT EXISTS vaccination_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS vaccine_schedule_approved_by BIGINT,
  ADD COLUMN IF NOT EXISTS vaccine_schedule_approved_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS vaccine_schedule_changed_at TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS vaccines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
  name VARCHAR(120) NOT NULL,
  protects_against VARCHAR(200) NOT NULL DEFAULT '',
  group_key VARCHAR(10) NOT NULL DEFAULT 'CHILD' CHECK (group_key IN ('CHILD','ADULT','TRAVEL')),
  price NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (price >= 0),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_vaccines_name ON vaccines (hospital_id, lower(name));

-- One row per dose of a vaccine: how old the patient is when it is due, the earliest age, and the minimum gap after the previous dose.
CREATE TABLE IF NOT EXISTS vaccine_schedule (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
  vaccine_id BIGINT NOT NULL REFERENCES vaccines(id),
  dose_no SMALLINT NOT NULL CHECK (dose_no BETWEEN 1 AND 20),
  label VARCHAR(40) NOT NULL DEFAULT '',
  due_age_days INTEGER NOT NULL CHECK (due_age_days BETWEEN 0 AND 40000),
  min_age_days INTEGER NOT NULL CHECK (min_age_days BETWEEN 0 AND 40000),
  min_gap_days INTEGER NOT NULL DEFAULT 0 CHECK (min_gap_days BETWEEN 0 AND 4000),
  UNIQUE (vaccine_id, dose_no)
);
CREATE INDEX IF NOT EXISTS idx_vaccine_schedule_hospital ON vaccine_schedule (hospital_id, vaccine_id);

CREATE TABLE IF NOT EXISTS patient_vaccinations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
  patient_id BIGINT NOT NULL REFERENCES patients(id),
  vaccine_id BIGINT NOT NULL REFERENCES vaccines(id),
  dose_no SMALLINT NOT NULL CHECK (dose_no BETWEEN 1 AND 20),
  status VARCHAR(16) NOT NULL CHECK (status IN ('GIVEN','SKIPPED','GIVEN_ELSEWHERE')),
  given_on DATE NOT NULL,
  batch_no VARCHAR(60) NOT NULL DEFAULT '',
  expiry_on DATE,
  site VARCHAR(40) NOT NULL DEFAULT '',
  brand VARCHAR(80) NOT NULL DEFAULT '',
  note VARCHAR(300) NOT NULL DEFAULT '',
  visit_id BIGINT REFERENCES visits(id),
  charge_id BIGINT,
  price_charged NUMERIC(10,2),
  recorded_by BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (patient_id, vaccine_id, dose_no)
);
CREATE INDEX IF NOT EXISTS idx_patient_vaccinations_patient ON patient_vaccinations (hospital_id, patient_id);
CREATE INDEX IF NOT EXISTS idx_patient_vaccinations_visit ON patient_vaccinations (hospital_id, visit_id);
