-- Online appointments. The hospital has one public booking page (/book/<slug>); patients pick a doctor and a free slot.
-- Nothing on the public side reads patient data: the page only receives doctor names and free times.
ALTER TABLE hospitals ADD COLUMN IF NOT EXISTS booking_slug VARCHAR(40);
ALTER TABLE hospitals ADD COLUMN IF NOT EXISTS booking_enabled BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE hospitals ADD COLUMN IF NOT EXISTS booking_advance_days INTEGER NOT NULL DEFAULT 7;
CREATE UNIQUE INDEX IF NOT EXISTS uq_hospitals_booking_slug ON hospitals(lower(booking_slug)) WHERE booking_slug IS NOT NULL;
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='hospitals'::regclass AND conname='hospitals_booking_advance_check') THEN
    ALTER TABLE hospitals ADD CONSTRAINT hospitals_booking_advance_check CHECK (booking_advance_days BETWEEN 1 AND 60);
  END IF;
END $$;

-- Each doctor is switched on for online booking separately
ALTER TABLE users ADD COLUMN IF NOT EXISTS online_booking BOOLEAN NOT NULL DEFAULT FALSE;

-- Weekly timings of a doctor for online booking. weekday: 0 = Sunday ... 6 = Saturday. A doctor can have more than one row
-- for a day (morning and evening). per_slot = how many patients can book the same slot.
CREATE TABLE IF NOT EXISTS doctor_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    doctor_id BIGINT NOT NULL,
    weekday SMALLINT NOT NULL CHECK (weekday BETWEEN 0 AND 6),
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    slot_minutes SMALLINT NOT NULL DEFAULT 15 CHECK (slot_minutes BETWEEN 5 AND 120),
    per_slot SMALLINT NOT NULL DEFAULT 1 CHECK (per_slot BETWEEN 1 AND 20),
    CHECK (end_time > start_time),
    FOREIGN KEY (hospital_id, doctor_id) REFERENCES users(hospital_id, id)
);
CREATE INDEX IF NOT EXISTS idx_doctor_schedules_doctor ON doctor_schedules(hospital_id, doctor_id, weekday);

CREATE TABLE IF NOT EXISTS doctor_days_off (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    doctor_id BIGINT NOT NULL,
    day DATE NOT NULL,
    note VARCHAR(120),
    FOREIGN KEY (hospital_id, doctor_id) REFERENCES users(hospital_id, id),
    UNIQUE (hospital_id, doctor_id, day)
);

CREATE TABLE IF NOT EXISTS appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    reference VARCHAR(10) NOT NULL,
    doctor_id BIGINT NOT NULL,
    slot_at TIMESTAMPTZ NOT NULL,
    slot_day DATE NOT NULL,                  -- the India-time day of the slot
    patient_id BIGINT,                        -- set when the booking came from a patient's own QR
    full_name VARCHAR(160) NOT NULL,
    mobile VARCHAR(10) NOT NULL,
    gender VARCHAR(20),
    date_of_birth DATE,
    dob_estimated BOOLEAN NOT NULL DEFAULT FALSE,
    reasons TEXT[] NOT NULL DEFAULT '{}',
    reason_note VARCHAR(200),
    status VARCHAR(12) NOT NULL DEFAULT 'BOOKED' CHECK (status IN ('BOOKED','ARRIVED','CANCELLED','NO_SHOW')),
    source VARCHAR(10) NOT NULL DEFAULT 'WEB' CHECK (source IN ('WEB','QR')),
    visit_id BIGINT,
    ip_hash VARCHAR(64),
    status_by BIGINT,
    status_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    FOREIGN KEY (hospital_id, doctor_id) REFERENCES users(hospital_id, id),
    UNIQUE (hospital_id, reference)
);
CREATE INDEX IF NOT EXISTS idx_appointments_day ON appointments(hospital_id, slot_day, doctor_id, slot_at);
CREATE INDEX IF NOT EXISTS idx_appointments_slot ON appointments(hospital_id, doctor_id, slot_at) WHERE status IN ('BOOKED','ARRIVED');
-- the same person cannot hold two live bookings with the same doctor on the same day
CREATE UNIQUE INDEX IF NOT EXISTS uq_appointments_person_day ON appointments(hospital_id, doctor_id, slot_day, mobile, lower(full_name)) WHERE status = 'BOOKED';

-- Short-lived counters used to slow down repeated booking attempts from one device or one mobile number
CREATE TABLE IF NOT EXISTS booking_hits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    kind VARCHAR(8) NOT NULL,
    key_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_booking_hits_key ON booking_hits(kind, key_hash, created_at);
