-- Support access: a hospital Admin creates a short code and reads it out to DhaCare support. Only after the Super Admin types the correct code
-- can they sign in to that hospital (as its Admin or as a user), for the time the hospital chose, and the hospital can end it at any moment.
-- One row per code and its session. A code is kept as a keyed hash, never as typed.
CREATE TABLE IF NOT EXISTS support_access (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    status VARCHAR(12) NOT NULL DEFAULT 'CODE' CHECK (status IN ('CODE','SESSION','ENDED','CANCELLED')),
    code_hash TEXT NOT NULL,
    code_expires_at TIMESTAMPTZ NOT NULL,
    attempts SMALLINT NOT NULL DEFAULT 0,
    session_minutes SMALLINT NOT NULL DEFAULT 60,
    created_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    superuser_id BIGINT,
    session_started_at TIMESTAMPTZ,
    session_ends_at TIMESTAMPTZ,
    ended_at TIMESTAMPTZ,
    ended_reason VARCHAR(20)
);
-- a hospital has at most one code or session open at a time
CREATE UNIQUE INDEX IF NOT EXISTS uq_support_access_open ON support_access (hospital_id) WHERE status IN ('CODE','SESSION');
CREATE INDEX IF NOT EXISTS idx_support_access_hospital ON support_access (hospital_id, created_at DESC);

-- what the support person did inside a session (shown to the hospital)
CREATE TABLE IF NOT EXISTS support_access_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    support_id BIGINT NOT NULL REFERENCES support_access(id) ON DELETE CASCADE,
    hospital_id BIGINT NOT NULL,
    action VARCHAR(20) NOT NULL,
    target_user_id BIGINT,
    target_name VARCHAR(160),
    target_role VARCHAR(20),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_support_events_support ON support_access_events (support_id, created_at);

