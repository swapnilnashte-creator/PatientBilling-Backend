-- Allergies are recorded once for the patient and shown on every later visit.
-- allergy_status: NOT_ASKED (nobody has asked yet), NONE ("no known allergies" was confirmed), LISTED (one or more allergies are on file).
ALTER TABLE patients
  ADD COLUMN IF NOT EXISTS allergy_status VARCHAR(10) NOT NULL DEFAULT 'NOT_ASKED',
  ADD COLUMN IF NOT EXISTS allergy_checked_at TIMESTAMPTZ,
  ADD COLUMN IF NOT EXISTS allergy_checked_by BIGINT;
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='patients'::regclass AND conname='patients_allergy_status_check') THEN
    ALTER TABLE patients ADD CONSTRAINT patients_allergy_status_check CHECK (allergy_status IN ('NOT_ASKED','NONE','LISTED'));
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS patient_allergies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
  patient_id BIGINT NOT NULL,
  name VARCHAR(80) NOT NULL,
  note VARCHAR(160),
  recorded_by BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  FOREIGN KEY (hospital_id, patient_id) REFERENCES patients(hospital_id, id),
  FOREIGN KEY (hospital_id, recorded_by) REFERENCES users(hospital_id, id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_patient_allergies_name ON patient_allergies (hospital_id, patient_id, lower(name));
CREATE INDEX IF NOT EXISTS idx_patient_allergies_patient ON patient_allergies (hospital_id, patient_id);
