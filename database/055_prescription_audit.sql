-- Every change to a prescription is recorded here: a medicine added, removed, or one of its details changed (dose, timing, days, note, content).
-- Who made it, when, and the details before and after. Rows are never edited by the app except to merge a few quick edits of the same medicine by the same person.
CREATE TABLE IF NOT EXISTS prescription_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    visit_id BIGINT NOT NULL,
    patient_id BIGINT NOT NULL,
    doctor_id BIGINT NOT NULL,                 -- the consulting doctor the medicine is stored under
    action VARCHAR(10) NOT NULL CHECK (action IN ('ADDED','REMOVED','CHANGED')),
    item_key VARCHAR(260) NOT NULL,            -- which medicine: its catalogue id, or its name for a custom one
    medicine_id BIGINT,
    name VARCHAR(200) NOT NULL,
    before_data JSONB,
    after_data JSONB,
    changed_fields TEXT[] NOT NULL DEFAULT '{}',
    changed_by BIGINT NOT NULL,
    changed_by_name VARCHAR(160) NOT NULL,
    changed_by_role VARCHAR(20) NOT NULL,
    by_support BOOLEAN NOT NULL DEFAULT FALSE, -- made inside a DhaCare support session
    visit_status VARCHAR(30) NOT NULL,         -- the visit's status at that moment (COMPLETED = edited after the visit was closed)
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_prescription_audit_patient ON prescription_audit (hospital_id, patient_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_prescription_audit_visit ON prescription_audit (hospital_id, visit_id, created_at);

