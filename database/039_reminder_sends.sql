-- Which WhatsApp reminders staff have already sent, so the next person can see it.
-- kind: FOLLOW_UP (ref = the visit id) or VACCINE (ref = the due date of the patient's earliest due dose).
-- A new follow-up or a new due dose has a new ref, so it shows as not sent again.
CREATE TABLE IF NOT EXISTS reminder_sends (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('FOLLOW_UP','VACCINE')),
    patient_id BIGINT NOT NULL,
    ref VARCHAR(40) NOT NULL,
    sent_by BIGINT NOT NULL,
    sent_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (hospital_id, kind, patient_id, ref),
    FOREIGN KEY (hospital_id, patient_id) REFERENCES patients(hospital_id, id),
    FOREIGN KEY (hospital_id, sent_by) REFERENCES users(hospital_id, id)
);
CREATE INDEX IF NOT EXISTS idx_reminder_sends_lookup ON reminder_sends(hospital_id, kind, patient_id);
