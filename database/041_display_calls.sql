-- Waiting room display, phase 2: a doctor calls a waiting patient (the TV highlights the token, plays a chime and can speak it),
-- and the Admin chooses the chime and the voice language.
ALTER TABLE hospitals ADD COLUMN IF NOT EXISTS display_voice VARCHAR(8) NOT NULL DEFAULT 'en';
ALTER TABLE hospitals ADD COLUMN IF NOT EXISTS display_chime BOOLEAN NOT NULL DEFAULT TRUE;
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='hospitals'::regclass AND conname='hospitals_display_voice_check') THEN
    ALTER TABLE hospitals ADD CONSTRAINT hospitals_display_voice_check CHECK (display_voice IN ('off','en','hi','mr'));
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS display_calls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    visit_id BIGINT NOT NULL,
    doctor_id BIGINT NOT NULL,
    token INTEGER,
    called_by BIGINT NOT NULL,
    called_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    FOREIGN KEY (hospital_id, visit_id) REFERENCES visits(hospital_id, id) ON DELETE CASCADE,
    FOREIGN KEY (hospital_id, doctor_id) REFERENCES users(hospital_id, id),
    FOREIGN KEY (hospital_id, called_by) REFERENCES users(hospital_id, id)
);
CREATE INDEX IF NOT EXISTS idx_display_calls_recent ON display_calls(hospital_id, called_at DESC);
