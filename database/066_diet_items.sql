-- The hospital's own master list of foods and drinks the dietitian picks from when writing a plan ("1 glass warm water with lemon").
-- DhaCare also offers a short built-in list of common items from the server (not stored here); this table holds only what the hospital adds.
CREATE TABLE IF NOT EXISTS diet_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
  name VARCHAR(200) NOT NULL,
  created_by BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_diet_items_name ON diet_items (hospital_id, lower(name));

