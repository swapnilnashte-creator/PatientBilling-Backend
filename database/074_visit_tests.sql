-- Tests advised: the tests a doctor asks the patient to get done, written on the prescription (one list per doctor per visit, like the medicines).
-- The test's name is copied, so an old prescription prints the same even if the list of common tests (backend/src/labTests.js) changes later.
-- test_code is the code from that list, or NULL for a test the doctor typed in. Only the advice is kept here: no results and no report files.
BEGIN;

CREATE TABLE IF NOT EXISTS visit_test_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
  visit_id BIGINT NOT NULL,
  doctor_id BIGINT NOT NULL,
  position INTEGER NOT NULL CHECK (position > 0),
  test_code VARCHAR(40),
  name VARCHAR(160) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (visit_id, doctor_id, position),
  FOREIGN KEY (hospital_id, visit_id) REFERENCES visits(hospital_id, id) ON DELETE CASCADE,
  FOREIGN KEY (hospital_id, doctor_id) REFERENCES users(hospital_id, id)
);
CREATE INDEX IF NOT EXISTS idx_visit_test_items_visit ON visit_test_items(hospital_id, visit_id);
CREATE INDEX IF NOT EXISTS idx_visit_test_items_doctor ON visit_test_items(hospital_id, doctor_id);

COMMIT;

