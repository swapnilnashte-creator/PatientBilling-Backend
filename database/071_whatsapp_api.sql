-- WhatsApp messages sent automatically through the paid Meta WhatsApp Cloud API (for example the appointment confirmation when a
-- patient books online). Only the Super Admin can switch it on or off for a hospital; it is off for every hospital to begin with.
-- Click-to-chat (staff tap WhatsApp and send from their own phone) is free and does not depend on this.
--
-- Each message is charged to the hospital at the rate per message in force when it was sent (the Super Admin sets it on the
-- Pricing page; Meta can change its price). Messages go on the hospital's next DhaCare invoice as their own line.
--
-- NEW TABLES: whatsapp_messages, platform_message_rates. On production grant SELECT, INSERT, UPDATE, DELETE on both to the app user.
ALTER TABLE hospitals ADD COLUMN IF NOT EXISTS whatsapp_api_enabled BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE hospitals ADD COLUMN IF NOT EXISTS whatsapp_api_changed_at TIMESTAMPTZ;
ALTER TABLE hospitals ADD COLUMN IF NOT EXISTS whatsapp_api_changed_by BIGINT;
-- The hospital's own switch (its Admin turns messages off or on again). Messages go out only when DhaCare allows them
-- (whatsapp_api_enabled) AND the hospital has them on. DhaCare's switch always wins: off there means nothing is sent.
ALTER TABLE hospitals ADD COLUMN IF NOT EXISTS whatsapp_api_hospital_on BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE hospitals ADD COLUMN IF NOT EXISTS whatsapp_api_hospital_changed_at TIMESTAMPTZ;
ALTER TABLE hospitals ADD COLUMN IF NOT EXISTS whatsapp_api_hospital_changed_by BIGINT;

-- The price of one message, in rupees. The newest row is the rate in force; older rows are the history.
CREATE TABLE IF NOT EXISTS platform_message_rates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rate NUMERIC(8,4) NOT NULL CHECK (rate > 0 AND rate <= 100),
  reason VARCHAR(500),
  created_by BIGINT REFERENCES platform_superusers(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
INSERT INTO platform_message_rates(rate, reason) SELECT 0.125, 'Starting rate' WHERE NOT EXISTS (SELECT 1 FROM platform_message_rates);

-- Every message DhaCare sends for a hospital through the Meta API, with the rate charged for it. A failed message is not charged.
-- invoice_id is set when the message is put on a hospital invoice, and cleared again if that invoice is cancelled.
CREATE TABLE IF NOT EXISTS whatsapp_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
  appointment_id BIGINT,
  kind VARCHAR(40) NOT NULL,
  template VARCHAR(120),
  to_mobile VARCHAR(15) NOT NULL,
  status VARCHAR(12) NOT NULL DEFAULT 'SENT' CHECK (status IN ('SENT','DELIVERED','READ','FAILED')),
  meta_message_id VARCHAR(160),
  error VARCHAR(300),
  rate NUMERIC(8,4) NOT NULL,
  sent_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  invoice_id BIGINT REFERENCES platform_invoices(id)
);
CREATE INDEX IF NOT EXISTS idx_whatsapp_messages_unbilled ON whatsapp_messages(hospital_id, sent_at) WHERE invoice_id IS NULL AND status <> 'FAILED';
CREATE INDEX IF NOT EXISTS idx_whatsapp_messages_invoice ON whatsapp_messages(invoice_id) WHERE invoice_id IS NOT NULL;

-- What an invoice charges for messages (a separate line on the invoice; already included in subtotal and total).
ALTER TABLE platform_invoices ADD COLUMN IF NOT EXISTS messages_count INTEGER NOT NULL DEFAULT 0;
ALTER TABLE platform_invoices ADD COLUMN IF NOT EXISTS messages_amount NUMERIC(12,2) NOT NULL DEFAULT 0;
ALTER TABLE platform_invoices ADD COLUMN IF NOT EXISTS messages_upto DATE;
ALTER TABLE platform_invoices ADD COLUMN IF NOT EXISTS messages_detail JSONB;

-- every switch and rate change is kept in the Super Admin audit
ALTER TABLE super_admin_audit_logs DROP CONSTRAINT IF EXISTS super_admin_audit_logs_action_check;
ALTER TABLE super_admin_audit_logs ADD CONSTRAINT super_admin_audit_logs_action_check CHECK (action IN (
  'LOGIN','IMPERSONATE_ADMIN','IMPERSONATE_USER','DEACTIVATE_HOSPITAL','ACTIVATE_HOSPITAL',
  'RATE_SCHEDULED','RATE_UPDATED','RATE_CANCELLED','HOSPITAL_BILLING_UPDATED',
  'INVOICE_CREATED','INVOICE_ISSUED','INVOICE_PAID','INVOICE_CANCELLED','COMPANY_DETAILS_UPDATED',
  'HOSPITAL_CREATED','HOSPITAL_DELETED','WHATSAPP_API_ENABLED','WHATSAPP_API_DISABLED','MESSAGE_RATE_UPDATED',
  'WHATSAPP_SENDING_ON','WHATSAPP_SENDING_OFF','REMINDER_DEFAULTS_UPDATED'));

-- The platform switch for all WhatsApp messages through Meta, set by the Super Admin (Pricing > WhatsApp messages). One row.
-- Off (the start) = nothing is sent for any hospital, whatever the hospital switches say. Turning it on or off is audited.
CREATE TABLE IF NOT EXISTS platform_whatsapp (
  id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  sending_on BOOLEAN NOT NULL DEFAULT FALSE,
  reason VARCHAR(500),
  changed_by BIGINT REFERENCES platform_superusers(id),
  changed_at TIMESTAMPTZ
);
INSERT INTO platform_whatsapp(id) VALUES (1) ON CONFLICT (id) DO NOTHING;

-- Reminder times. DhaCare's defaults (Super Admin, Pricing > WhatsApp messages) apply to every hospital that has not chosen its own.
-- appointment: hours before the appointment. followUp / vaccination: days before the date, at this hour (India time).
ALTER TABLE platform_whatsapp ADD COLUMN IF NOT EXISTS reminder_defaults JSONB NOT NULL
  DEFAULT '{"appointment":{"hours":24},"followUp":{"days":1,"hour":10},"vaccination":{"days":2,"hour":10}}';
-- The hospital's own choices (Hospital Settings > Subscription > WhatsApp): each reminder on or off, and only the times that differ from
-- DhaCare's defaults are kept, so a later change of a default still reaches the hospital. NULL = all defaults, all on.
ALTER TABLE hospitals ADD COLUMN IF NOT EXISTS whatsapp_reminders JSONB;

-- which patient a reminder was for, and what it was about (the follow-up visit or the vaccine due date), so it is sent only once
ALTER TABLE whatsapp_messages ADD COLUMN IF NOT EXISTS patient_id BIGINT;
ALTER TABLE whatsapp_messages ADD COLUMN IF NOT EXISTS ref VARCHAR(40);
CREATE INDEX IF NOT EXISTS idx_whatsapp_messages_ref ON whatsapp_messages(hospital_id, kind, ref) WHERE ref IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_whatsapp_messages_appointment ON whatsapp_messages(appointment_id) WHERE appointment_id IS NOT NULL;
