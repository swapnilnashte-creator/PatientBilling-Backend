-- Dietitians: a client's diet programme with a daily weight and a plan for each week.
-- The speciality DIETITIAN is added to the allowed list. New tables: after running this as the admin database user, grant the app user access (line at the end).

ALTER TABLE users DROP CONSTRAINT IF EXISTS users_speciality_check;
ALTER TABLE users ADD CONSTRAINT users_speciality_check CHECK (speciality IS NULL OR speciality IN
  ('GENERAL_PHYSICIAN','PAEDIATRICIAN','DIETITIAN','DENTIST','GYNAECOLOGIST','ORTHOPAEDIC','ENT','DERMATOLOGIST','OTHER'));

-- A client followed by one dietitian. Weeks are counted from start_date in blocks of 7 days.
CREATE TABLE IF NOT EXISTS diet_programmes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
  patient_id BIGINT NOT NULL,
  doctor_id BIGINT NOT NULL,
  start_date DATE NOT NULL,
  goal_weight_kg NUMERIC(5,1) CHECK (goal_weight_kg IS NULL OR goal_weight_kg BETWEEN 10 AND 300),
  goal_date DATE,
  food_pattern VARCHAR(10) CHECK (food_pattern IS NULL OR food_pattern IN ('VEG','EGG','NONVEG','JAIN','VEGAN','OTHER')),
  reasons VARCHAR(300),
  notes TEXT,
  status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','PAUSED','COMPLETED')),
  ended_on DATE,
  created_by BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_diet_programmes_doctor ON diet_programmes(hospital_id, doctor_id, status);
CREATE INDEX IF NOT EXISTS idx_diet_programmes_patient ON diet_programmes(hospital_id, patient_id);
-- one running programme for a client with a dietitian
CREATE UNIQUE INDEX IF NOT EXISTS uq_diet_programme_running ON diet_programmes(hospital_id, patient_id, doctor_id) WHERE status <> 'COMPLETED';

-- One weight per client per day. Entering the day again replaces it (the change goes to diet_history).
CREATE TABLE IF NOT EXISTS weight_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
  patient_id BIGINT NOT NULL,
  on_date DATE NOT NULL,
  weight_kg NUMERIC(5,1) NOT NULL CHECK (weight_kg BETWEEN 10 AND 300),
  entered_by BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (hospital_id, patient_id, on_date)
);

-- The plan for one week of a programme (week_start is start_date plus a multiple of 7 days). meals is a list of { slot, text }.
-- "Same plan again" is a copy of last week's row (how_made SAME), so each week keeps exactly what was given.
CREATE TABLE IF NOT EXISTS diet_plan_weeks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
  programme_id BIGINT NOT NULL REFERENCES diet_programmes(id) ON DELETE CASCADE,
  week_start DATE NOT NULL,
  meals JSONB NOT NULL DEFAULT '[]',
  kcal INTEGER CHECK (kcal IS NULL OR kcal BETWEEN 300 AND 6000),
  protein_g INTEGER CHECK (protein_g IS NULL OR protein_g BETWEEN 5 AND 400),
  instructions TEXT,
  how_made VARCHAR(6) NOT NULL DEFAULT 'NEW' CHECK (how_made IN ('NEW','SAME','EDITED')),
  copied_from_week_id BIGINT,
  review_note TEXT,
  reviewed_at TIMESTAMPTZ,
  reviewed_by BIGINT,
  created_by BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (hospital_id, programme_id, week_start)
);

-- The hospital's own starting points for a plan ("1500 kcal vegetarian"). DhaCare ships none.
CREATE TABLE IF NOT EXISTS diet_plan_templates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
  name VARCHAR(120) NOT NULL,
  kcal INTEGER CHECK (kcal IS NULL OR kcal BETWEEN 300 AND 6000),
  meals JSONB NOT NULL DEFAULT '[]',
  instructions TEXT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_diet_plan_templates_name ON diet_plan_templates (hospital_id, lower(name));

-- Every changed or removed weight and every changed plan: who, when, before and after.
CREATE TABLE IF NOT EXISTS diet_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
  programme_id BIGINT NOT NULL,
  kind VARCHAR(10) NOT NULL CHECK (kind IN ('WEIGHT','PLAN')),
  ref_date DATE NOT NULL,
  action VARCHAR(10) NOT NULL,
  before_data JSONB,
  after_data JSONB,
  changed_by BIGINT,
  changed_by_name VARCHAR(120),
  changed_by_role VARCHAR(20),
  by_support BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_diet_history_programme ON diet_history(hospital_id, programme_id, created_at DESC);

