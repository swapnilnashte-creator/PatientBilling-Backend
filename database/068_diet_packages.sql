-- Dietitians: a package a client pays for (monthly, quarterly, yearly or any dates), paid in instalments.
-- A package belongs to the programme. The visits inside its dates are counted against it; an optional consult limit is set by the dietitian.
-- New tables: after running this as the admin database user, grant the app user access (line at the end).

CREATE TABLE IF NOT EXISTS diet_packages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
  programme_id BIGINT NOT NULL REFERENCES diet_programmes(id) ON DELETE CASCADE,
  patient_id BIGINT NOT NULL,
  doctor_id BIGINT NOT NULL,
  name VARCHAR(60) NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
  consult_limit SMALLINT CHECK (consult_limit IS NULL OR consult_limit BETWEEN 1 AND 365),
  notes VARCHAR(300),
  status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','CANCELLED')),
  created_by BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (end_date >= start_date)
);
CREATE INDEX IF NOT EXISTS idx_diet_packages_programme ON diet_packages(hospital_id, programme_id, start_date);
CREATE INDEX IF NOT EXISTS idx_diet_packages_patient ON diet_packages(hospital_id, patient_id, start_date);

-- Each instalment received. paid_on is the day the money came in (it decides the day the income counts).
CREATE TABLE IF NOT EXISTS diet_package_payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
  package_id BIGINT NOT NULL REFERENCES diet_packages(id) ON DELETE CASCADE,
  amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
  payment_mode VARCHAR(20) NOT NULL CHECK (payment_mode IN ('CASH','UPI','CARD','OTHER')),
  reference_no VARCHAR(120),
  paid_on DATE NOT NULL,
  accepted_by BIGINT,
  accepted_by_name VARCHAR(120),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_diet_package_payments_package ON diet_package_payments(hospital_id, package_id);
CREATE INDEX IF NOT EXISTS idx_diet_package_payments_day ON diet_package_payments(hospital_id, paid_on);

-- package changes and payments join the programme's history
ALTER TABLE diet_history DROP CONSTRAINT IF EXISTS diet_history_kind_check;
ALTER TABLE diet_history ADD CONSTRAINT diet_history_kind_check CHECK (kind IN ('WEIGHT','PLAN','PACKAGE'));

