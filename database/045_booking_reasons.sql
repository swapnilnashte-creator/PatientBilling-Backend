-- Reasons for a visit that patients choose from when booking online. Each hospital keeps its own list, and each reason has a severity
-- (LOW = normal, MEDIUM = moderate, HIGH = urgent) shown as a colour to the staff.
CREATE TABLE IF NOT EXISTS booking_reasons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
    name VARCHAR(60) NOT NULL,
    severity VARCHAR(6) NOT NULL DEFAULT 'LOW' CHECK (severity IN ('LOW','MEDIUM','HIGH')),
    position INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_booking_reasons_name ON booking_reasons(hospital_id, lower(name));
CREATE INDEX IF NOT EXISTS idx_booking_reasons_order ON booking_reasons(hospital_id, position);

-- the most serious severity among the reasons the patient chose
ALTER TABLE appointments ADD COLUMN IF NOT EXISTS severity VARCHAR(6) NOT NULL DEFAULT 'LOW';
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='appointments'::regclass AND conname='appointments_severity_check') THEN
    ALTER TABLE appointments ADD CONSTRAINT appointments_severity_check CHECK (severity IN ('LOW','MEDIUM','HIGH'));
  END IF;
END $$;
