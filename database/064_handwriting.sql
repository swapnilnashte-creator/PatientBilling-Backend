-- Writing by hand: a doctor can write the prescription (or notes) with a pen tablet or stylus, and it prints on the pad as their handwriting.
-- It is off for every hospital until the Admin turns it on in Hospital Settings, so nothing changes for clinics that do not use it.
-- strokes holds the pen strokes as [{"p": [[x, y, pressure], ...]}, ...] on a sheet 1000 units wide (see frontend/src/components/HandwritingPad.jsx); a page is about 6-20 KB.
ALTER TABLE hospitals ADD COLUMN IF NOT EXISTS handwriting_enabled BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS visit_handwriting (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id BIGINT NOT NULL REFERENCES hospitals(id),
  visit_id BIGINT NOT NULL,
  doctor_id BIGINT NOT NULL,
  strokes JSONB NOT NULL DEFAULT '[]'::jsonb,
  stroke_count INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (hospital_id, visit_id, doctor_id),
  FOREIGN KEY (hospital_id, visit_id) REFERENCES visits(hospital_id, id) ON DELETE CASCADE,
  FOREIGN KEY (hospital_id, doctor_id) REFERENCES users(hospital_id, id)
);

